#!/usr/bin/env bash
# =====================================================================
#  Быстрая проверка проекта: источники, синтаксис, unittest-тесты.
#
#  Запуск:
#      bash scripts/check.sh
#
#  Источники проверяются по сети: если интернет недоступен, будет
#  предупреждение (это не ошибка установки). Тесты — обязательны:
#  их падение даёт код выхода 1.
# =====================================================================
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$ROOT"

VENV_PY="$ROOT/.venv/bin/python"
if [ ! -x "$VENV_PY" ]; then
    echo "ОШИБКА: не найдено виртуальное окружение .venv."
    echo "Сначала выполните: bash scripts/install.sh"
    exit 1
fi

FAILED=0

echo "===================================================================="
echo " Проверка контент-завода"
echo "===================================================================="
echo

# --- 1. Конфигурация ---------------------------------------------------
echo "[1/4] Конфигурация каналов ..."
if "$VENV_PY" -m content_factory channels; then
    echo "      OK: конфигурация загружается."
else
    echo "      ОШИБКА: проверьте config/channels.yaml и config/settings.yaml."
    FAILED=1
fi
echo

# --- 2. Синтаксис Python ----------------------------------------------
echo "[2/4] Синтаксис Python-модулей ..."
if "$VENV_PY" -m compileall -q content_factory; then
    echo "      OK: синтаксис в порядке."
else
    echo "      ОШИБКА: есть модули с синтаксическими ошибками."
    FAILED=1
fi
echo

# --- 3. Источники (сеть, необязательно) -------------------------------
echo "[3/4] Доступность источников ..."
"$VENV_PY" -m content_factory sources check
SOURCES_STATUS=$?
if [ "$SOURCES_STATUS" -eq 0 ]; then
    echo "      OK: источники отвечают."
else
    echo "      ВНИМАНИЕ: часть источников недоступна (сеть/блокировки)."
    echo "      Это не мешает работе, но такие источники не дадут новостей."
fi
echo

# --- 4. Тесты ----------------------------------------------------------
echo "[4/4] Тесты (unittest) ..."
if "$VENV_PY" -m unittest discover -s tests -t . -v; then
    echo "      OK: тесты прошли."
else
    echo "      ОШИБКА: тесты упали. Подробности выше."
    FAILED=1
fi
echo

echo "===================================================================="
if [ "$FAILED" -eq 0 ]; then
    echo " Проверка завершена: критичных проблем нет."
    echo " Логи: data/logs/factory.log"
    exit 0
else
    echo " Проверка завершена С ОШИБКАМИ. Смотрите сообщения выше."
    exit 1
fi

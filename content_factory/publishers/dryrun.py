class DryRunPublisher(Publisher):
    """Пишет пост в data/outbox вместо реальной публикации."""

    name = "dryrun"

    # ------------------------------------------------------------------
    # публичный интерфейс
    # ------------------------------------------------------------------
    def publish(
        self, post: GeneratedPost, channel: ChannelConfig, settings: Settings
    ) -> PublishResult:
        try:
            outbox = Path(settings.outbox_dir)
            channel_dir = ensure_dir(outbox / _safe_name(channel.id))
            created = _aware(post.created_at)
            day = created.astimezone(channel.local_tz).strftime("%Y-%m-%d")
            stem = "{}-{}".format(day, _safe_name(post.id))
            txt_path = channel_dir / (stem + ".txt")
            html_path = channel_dir / (stem + ".html")

            atomic_write_text(txt_path, self._render_text(post, channel))
            atomic_write_text(html_path, self._render_html(post, channel))
            logger.info(
                "DRY RUN: пост %s канала %s сохранён в %s",
                post.id,
                channel.id,
                txt_path,
            )
            return self._result(
                post,
                channel,
                ok=True,
                external_id=str(txt_path),
                url=str(html_path),
                dry_run=True,
            )
        except Exception as exc:  # noqa: BLE001 - наружу не падаем
            logger.exception("DRY RUN: не удалось сохранить предпросмотр поста %s", post.id)
            return self._result(
                post,
                channel,
                ok=False,
                error="Не удалось сохранить dry-run предпросмотр: {}".format(exc),
                dry_run=True,
            )

    def check(self) -> Tuple[bool, str]:
        return (
            True,
            "Dry-run включён: сообщения не отправляются, предпросмотры пишутся в {}".format(
                self.settings.outbox_dir
            ),
        )

    # ------------------------------------------------------------------
    # рендер файлов
    # ------------------------------------------------------------------
    def _render_text(self, post: GeneratedPost, channel: ChannelConfig) -> str:
        labels = _labels(channel)
        created = _aware(post.created_at).astimezone(channel.local_tz)
        lines = [
            labels["not_sent"],
            "=" * 60,
            "{}: {} ({})".format(labels["channel"], channel.title, channel.id),
            "{}: {}".format(labels["format"], post.format),
            "{}: {}".format(labels["created"], created.strftime(labels["date"])),
            "{}: {}".format(labels["post_id"], post.id),
            "{}: {}".format(labels["cluster"], post.cluster_id or "-"),
            "=" * 60,
            "",
            _html_to_text(post.text),
        ]
        if post.hashtags:
            lines.extend(["", "{}: {}".format(labels["hashtags"], " ".join(post.hashtags))])
        if post.sources:
            lines.extend(["", "{}:".format(labels["sources"])])
            for source in post.sources:
                title = source.get("title") or source.get("source") or labels["source_fallback"]
                url = source.get("url") or ""
                lines.append("- {}: {} {}".format(source.get("source", ""), title, url).strip())
        image_url = str((post.meta or {}).get("image_url") or "").strip()
        if image_url:
            lines.extend(["", "{}: {}".format(labels["image"], image_url)])
        if post.meta:
            lines.extend(["", "{}: generator={}, tone={}".format(
                labels["metadata"],
                post.meta.get("generator", "-"),
                post.meta.get("tone", "-"),
            )])
        lines.append("")
        lines.append(labels["preview_hint"].format(
            "{}-{}".format(
                _aware(post.created_at).astimezone(channel.local_tz).strftime("%Y-%m-%d"),
                _safe_name(post.id),
            )
        ))
        return "\n".join(lines) + "\n"

    def _render_html(self, post: GeneratedPost, channel: ChannelConfig) -> str:
        labels = _labels(channel)
        created = _aware(post.created_at).astimezone(channel.local_tz)
        sources_html = ""
        if post.sources:
            items = []
            for source in post.sources:
                title = html_escape(str(
                    source.get("title") or source.get("source") or labels["source_fallback"]
                ))
                url = str(source.get("url") or "").strip()
                source_name = html_escape(str(source.get("source") or ""))
                label = "{}: {}".format(source_name, title) if source_name else title
                if url.startswith(("http://", "https://")):
                    items.append('<li><a href="{}">{}</a></li>'.format(
                        html_escape(url), label
                    ))
                else:
                    items.append("<li>{}</li>".format(label))
            sources_html = "<h2>{}</h2><ul>{}</ul>".format(
                labels["sources"], "".join(items)
            )
        image_html = ""
        image_url = str((post.meta or {}).get("image_url") or "").strip()
        if image_url.startswith(("http://", "https://")):
            image_html = '<img class="post-image" src="{}" alt="post image">'.format(
                html_escape(image_url)
            )
        tags_html = ""
        if post.hashtags:
            tags_html = '<div class="tags">{}</div>'.format(
                html_escape(" ".join(post.hashtags))
            )
        meta_html = ""
        if post.meta:
            meta_html = '<p class="meta">{}: {} · {}: {} · {}: {}</p>'.format(
                labels["generator"],
                html_escape(str(post.meta.get("generator", labels["template_generator"]))),
                labels["tone"],
                html_escape(str(post.meta.get("tone", channel.tone))),
                labels["score"],
                html_escape(str(post.score)),
            )
        return """<!DOCTYPE html>
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>DRY RUN — {title} — {post_id}</title>
<style>{css}</style>
</head>
<body>
<div class="wrap">
  <span class="badge">{badge}</span>
  <div class="card">
    <h1>{title}</h1>
    <p class="meta">{channel_label}: {title} ({channel_id}) · {format_label}: {post_format} · {date}</p>
    {meta_html}
    {image_html}
    <div class="post-body">{body}</div>
    {tags_html}
    {sources_html}
  </div>
  <p class="footer">{footer}</p>
</div>
</body>
</html>
""".format(
            lang=labels["html_lang"],
            title=html_escape(channel.title),
            post_id=html_escape(post.id),
            css=_PREVIEW_CSS,
            badge=labels["html_badge"],
            channel_label=labels["channel"],
            channel_id=html_escape(channel.id),
            format_label=labels["format"],
            post_format=html_escape(post.format),
            date=html_escape(created.strftime(labels["html_date"])),
            meta_html=meta_html,
            image_html=image_html,
            body=post.text,
            tags_html=tags_html,
            sources_html=sources_html,
            footer=labels["footer"],
        )

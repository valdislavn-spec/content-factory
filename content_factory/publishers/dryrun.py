def _html_to_text(fragment: str) -> str:
    """HTML → читаемый текст с сохранением абзацев (для .txt-предпросмотра)."""
    text = str(fragment or "")
    text = re.sub(r"<br\s*/?>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"</(?:p|div|li|h[1-6]|tr|blockquote)>", "\n", text, flags=re.IGNORECASE)
    text = re.sub(r"<li[^>]*>", "• ", text, flags=re.IGNORECASE)
    text = re.sub(r"<[^>]+>", "", text)
    text = html_lib.unescape(text)
    lines = []
    for line in text.splitlines():
        line = re.sub(r"[ \t\u00a0]+", " ", line).strip()
        if line:
            lines.append(line)
    return "\n".join(lines)


def _safe_name(value: str) -> str:
    name = _SAFE_NAME_RE.sub("-", str(value or "")).strip("-._")
    return (name or "post")[:80]


def _aware(value) -> "object":
    """Гарантирует timezone-aware datetime (по умолчанию — UTC)."""
    if value is None:
        from ..models import utcnow

        return utcnow()
    if getattr(value, "tzinfo", None) is None:
        return value.replace(tzinfo=timezone.utc)
    return value


